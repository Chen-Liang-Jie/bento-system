-- ---------------------------------------------------------------------
-- 1. 商品資料表 products
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.products (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          TEXT        NOT NULL,
  category      TEXT        DEFAULT '招牌便當',
  diet_type     TEXT        DEFAULT '全素'
                CHECK (diet_type IN ('全素', '蛋素', '奶素', '蛋奶素')),
  price         INTEGER     NOT NULL CHECK (price >= 0),
  stock         INTEGER     NOT NULL DEFAULT 30 CHECK (stock >= 0),
  is_available  BOOLEAN     NOT NULL DEFAULT true,
  pos_code      TEXT,                                   -- 預留給傳統 POS 串接用
  created_at    TIMESTAMPTZ DEFAULT NOW()
);


-- ---------------------------------------------------------------------
-- 2. 訂單資料表 orders
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.orders (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_no         TEXT        NOT NULL,                -- 當日流水號，如 #001
  customer_name    TEXT        NOT NULL,
  customer_phone   TEXT        NOT NULL,
  order_type       TEXT        DEFAULT '外帶自取',
  pickup_time      TEXT        DEFAULT '立即製作',
  items_json       JSONB       NOT NULL,
  total_amount     INTEGER     NOT NULL CHECK (total_amount >= 0),
  status           TEXT        NOT NULL DEFAULT 'PENDING'
                   CHECK (status IN ('PENDING', 'PREPARING', 'COMPLETED', 'CANCELLED')),
  is_paid          BOOLEAN     NOT NULL DEFAULT false,
  pos_sync_status  BOOLEAN     NOT NULL DEFAULT false,  -- 預留 POS 同步標記
  created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 訂單佇列一律依訂餐時間由早到晚排序（created_at ASC）
CREATE INDEX IF NOT EXISTS idx_orders_created_at ON public.orders (created_at ASC);


