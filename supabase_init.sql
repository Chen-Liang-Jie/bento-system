REVOKE ALL ON FUNCTION public.cancel_bento_order(BIGINT)                         FROM PUBLIC;
REVOKE ALL ON FUNCTION public.adjust_product_stock(BIGINT, INTEGER)              FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.create_bento_order(TEXT, TEXT, TEXT, TEXT, JSONB) TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.cancel_bento_order(BIGINT)                         TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.adjust_product_stock(BIGINT, INTEGER)              TO anon, authenticated;


-- ---------------------------------------------------------------------
-- 5-1. Realtime 即時推播（已加入過則略過，避免重複執行時報錯）
-- ---------------------------------------------------------------------
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables
    WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'products'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.products;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables
    WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'orders'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.orders;
  END IF;
END;
$$;


-- ---------------------------------------------------------------------
-- 5-2. RLS 權限（MVP 階段）
--
-- ⚠ 注意：目前後台只有前端 PIN 碼鎖，沒有真正的帳號登入，
--   所以任何拿到網頁中 anon key 的人，理論上都能直接呼叫 API：
--     - 讀取所有訂單（含顧客姓名、電話）
--     - 修改商品（名稱、價格、庫存）與訂單狀態
--   正式營運前，建議改用 Supabase Auth 讓店家登入，再把下面的
--   寫入權限從 anon 收回、只開放給 authenticated。
--
-- 已先做的防護：
--   * 顧客不能直接 INSERT 訂單，只能透過 create_bento_order 下單（金額由資料庫計算）。
--   * 訂單只開放修改 status / is_paid / pos_sync_status 三個欄位，
--     不能竄改金額、品項或顧客資料。
--   * 訂單不開放刪除（取消請用 cancel_bento_order，保留營收紀錄並歸還庫存）。
-- ---------------------------------------------------------------------
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders   ENABLE ROW LEVEL SECURITY;

-- 欄位層級權限
REVOKE TRUNCATE ON public.products FROM anon, authenticated;
REVOKE INSERT, UPDATE, DELETE, TRUNCATE ON public.orders FROM anon, authenticated;
GRANT SELECT ON public.orders TO anon, authenticated;
GRANT UPDATE (status, is_paid, pos_sync_status) ON public.orders TO anon, authenticated;

-- products：所有人可讀；後台可新增、修改、刪除商品
DROP POLICY IF EXISTS "products_select_all" ON public.products;
DROP POLICY IF EXISTS "products_insert_mvp" ON public.products;
DROP POLICY IF EXISTS "products_update_mvp" ON public.products;
DROP POLICY IF EXISTS "products_delete_mvp" ON public.products;

CREATE POLICY "products_select_all" ON public.products
  FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "products_insert_mvp" ON public.products
  FOR INSERT TO anon, authenticated WITH CHECK (true);
CREATE POLICY "products_update_mvp" ON public.products
  FOR UPDATE TO anon, authenticated USING (true) WITH CHECK (true);
CREATE POLICY "products_delete_mvp" ON public.products
  FOR DELETE TO anon, authenticated USING (true);

-- orders：所有人可讀（後台佇列與 Realtime 推播需要）；只能改狀態欄位
